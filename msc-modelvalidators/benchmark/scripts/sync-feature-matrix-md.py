#!/usr/bin/env python3
"""Regenerate docs/modelvalidator-feature-matrix.md from
docs/modelvalidator-feature-matrix.json.

The .json is the single source of truth (schema documented at the top of
that file); the .md is a pure, mechanical rendering of it for human reading
on GitHub. Never hand-edit the .md -- edit the .json (or use
sync-manifest-features.py / scan-scenario-features.py to help populate it),
then re-run this script. Previously this was a one-off scratchpad script
that had to be reconstructed by hand more than once in the same thesis
session; it now lives in the repo so that doesn't happen again.

Usage: python3 sync-feature-matrix-md.py [path/to/modelvalidator-feature-matrix.json]
       (defaults to ../../../docs/modelvalidator-feature-matrix.json relative to this script)
"""
import json
import sys
from pathlib import Path

STATUS_LABEL = {
    "supported": "Supported",
    "known-defect": "Known defect",
    "degraded": "Degraded",
    "unsupported": "Unsupported",
    "unverified": "Unverified",
}
EVIDENCE_TRUNCATE = 200


def esc(cell):
    """Markdown table cells can't contain a literal '|' or newline."""
    return str(cell).replace("|", "\\|").replace("\n", " ").strip()


def join_ids(ids):
    return ", ".join(ids) if ids else "\u2014"


def truncate(text):
    text = (text or "").strip()
    if len(text) <= EVIDENCE_TRUNCATE:
        return text
    return text[:EVIDENCE_TRUNCATE].rstrip() + "..."


def describe_scenario_count(manifest_path):
    if not manifest_path.is_file():
        return "see manifest.json"
    examples = json.loads(manifest_path.read_text(encoding="utf-8"))["examples"]
    unsat = sum(1 for ex in examples if ex["id"].endswith("-UNSAT"))
    base = len(examples) - unsat
    return f"{base} base scenarios + {unsat} paired UNSAT mutations"


def render(matrix, scenario_count):
    plugins = matrix["plugins"]
    areas = matrix["areas"]
    total_features = sum(len(a["features"]) for a in areas)

    lines = []
    lines.append("# Model-validator plugin feature matrix")
    lines.append("")
    lines.append(
        "Versioned, machine-checkable capability inventory shared across every model-validator "
        "plugin in this thesis, cross-mapped against the scenarios in "
        f"`msc-modelvalidators/benchmark/src/main/resources/manifest.json ({scenario_count})`. "
        "Each feature is scored "
        "per plugin under its own `support` entry, so a second plugin's capability data slots in "
        "next to the first without restructuring anything -- see "
        "[modelvalidator-feature-matrix.json](modelvalidator-feature-matrix.json) for the "
        "machine-readable form (same data, one row per feature per plugin, with full evidence "
        "strings)."
    )
    lines.append("")
    lines.append(
        "This is a *support* inventory, not a *correctness proof*: a status means \"this is what "
        "the source code and/or a real example run demonstrates\" for that specific plugin -- "
        "re-verify any row you plan to rely on for a claim in the thesis itself by following its "
        "evidence pointer."
    )
    lines.append("")
    lines.append("_Generated by `scripts/sync-feature-matrix-md.py` from the .json -- do not hand-edit._")
    lines.append("")

    lines.append("## Plugins tracked")
    lines.append("")
    lines.append("| ID | Name | Status | Description |")
    lines.append("|---|---|---|---|")
    for p in plugins:
        lines.append(f"| `{p['id']}` | {esc(p['name'])} | {esc(p['status'])} | {esc(p.get('description', ''))} |")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append(f"- **{total_features} features** inventoried across **{len(areas)} capability areas**.")
    for p in plugins:
        counts = {k: 0 for k in STATUS_LABEL}
        evaluated = 0
        for area in areas:
            for f in area["features"]:
                sup = f["support"].get(p["id"])
                if sup:
                    evaluated += 1
                    counts[sup["status"]] = counts.get(sup["status"], 0) + 1
        if evaluated == 0:
            lines.append(f"- **{esc(p['name'])}**: not yet evaluated (0/{total_features}).")
        else:
            parts = ", ".join(
                f"**{counts[k]}** {STATUS_LABEL[k].lower()}" for k in STATUS_LABEL if counts.get(k)
            )
            lines.append(f"- **{esc(p['name'])}**: {evaluated}/{total_features} evaluated -- {parts}.")
    lines.append("")

    # The main per-area table renders one plugin in full (status/SAT/UNSAT/oracle/evidence) --
    # the first plugin registered, by convention. Every OTHER plugin gets a compact extra status
    # column in that same table (so a side-by-side comparison is visible at a glance) plus its own
    # full evidence in a per-area <details> block (so nothing is lost, without making the main
    # table unreadably wide with N plugins x 5 columns each).
    primary_plugin = plugins[0]["id"] if plugins else None
    secondary_plugins = plugins[1:]
    for area in areas:
        lines.append(f"## {esc(area['name'])}")
        lines.append("")
        header = ["Feature ID", "Name", "Status", "SAT", "UNSAT", "Oracle", "Evidence"]
        for p in secondary_plugins:
            header.append(f"{esc(p['name'])} status")
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|" + "---|" * len(header))
        zero_coverage = []
        secondary_evidence = {p["id"]: [] for p in secondary_plugins}
        for f in area["features"]:
            sup = f["support"].get(primary_plugin) if primary_plugin else None
            row_prefix = f"| `{f['id']}` | {esc(f['name'])} | "
            if not sup:
                row = row_prefix + "Unverified | \u2014 | \u2014 | \u2014 | \u2014 |"
            else:
                sat = sup.get("satScenarioIds") or []
                unsat = sup.get("unsatScenarioIds") or []
                val = sup.get("validationOracleScenarioIds") or []
                if not (sat or unsat or val):
                    zero_coverage.append((f["id"], sup.get("coverageNote", "") or "zero coverage"))
                row = (
                    row_prefix
                    + f"{STATUS_LABEL.get(sup['status'], esc(sup['status']))} | "
                    f"{esc(join_ids(sat))} | {esc(join_ids(unsat))} | {esc(join_ids(val))} | "
                    f"{esc(truncate(sup.get('evidence', '')))} |"
                )
            for p in secondary_plugins:
                sec = f["support"].get(p["id"])
                if sec:
                    row += f" {STATUS_LABEL.get(sec['status'], esc(sec['status']))} |"
                    secondary_evidence[p["id"]].append((f["id"], f["name"], sec))
                else:
                    row += " Unverified |"
            lines.append(row)
        lines.append("")
        if zero_coverage:
            lines.append(f"<details><summary>Zero-coverage features in this area ({len(zero_coverage)})</summary>")
            lines.append("")
            for fid, note in zero_coverage:
                lines.append(f"- `{fid}` \u2014 {esc(note)}")
            lines.append("")
            lines.append("</details>")
            lines.append("")
        for p in secondary_plugins:
            entries = secondary_evidence[p["id"]]
            if not entries:
                continue
            lines.append(
                f"<details><summary>{esc(p['name'])} evidence for this area ({len(entries)})</summary>"
            )
            lines.append("")
            lines.append("| Feature ID | Name | Status | SAT | UNSAT | Oracle | Evidence |")
            lines.append("|---|---|---|---|---|---|---|")
            for fid, fname, sec in entries:
                sat = sec.get("satScenarioIds") or []
                unsat = sec.get("unsatScenarioIds") or []
                val = sec.get("validationOracleScenarioIds") or []
                lines.append(
                    f"| `{fid}` | {esc(fname)} | {STATUS_LABEL.get(sec['status'], esc(sec['status']))} | "
                    f"{esc(join_ids(sat))} | {esc(join_ids(unsat))} | {esc(join_ids(val))} | "
                    f"{esc(truncate(sec.get('evidence', '')))} |"
                )
            lines.append("")
            lines.append("</details>")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main():
    repo_root = Path(__file__).resolve().parents[3]
    default_path = repo_root / "docs" / "modelvalidator-feature-matrix.json"
    json_path = Path(sys.argv[1]) if len(sys.argv) > 1 else default_path
    md_path = json_path.with_suffix(".md")
    manifest_path = repo_root / "msc-modelvalidators" / "benchmark" / "src" / "main" / "resources" / "manifest.json"

    matrix = json.loads(json_path.read_text(encoding="utf-8"))
    md_path.write_text(render(matrix, describe_scenario_count(manifest_path)), encoding="utf-8")
    print(f"Wrote {md_path}")


if __name__ == "__main__":
    main()
